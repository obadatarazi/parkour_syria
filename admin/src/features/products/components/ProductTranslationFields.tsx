import { useEffect, useState } from "react";

import { TextAreaField, TextField } from "@/shared/components";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/shared/design-system/components/ui/tabs";
import { useTranslation } from "@/shared/design-system/localization/contexts/LocalizationContext";
import type { ProductTranslationsInput } from "@/shared/lib/api/form-data.utils";
import {
  getPredictedProductSlug,
  shouldAutoSuggestProductSlug,
} from "@/features/products/utils/product-slug.utils";

type ProductTranslationFieldsProps = {
  value: ProductTranslationsInput;
  onChange: (value: ProductTranslationsInput) => void;
  titleErrors?: Partial<Record<"en" | "ar", string>>;
  showSlugPreview?: boolean;
  autoFocusFirstField?: boolean;
  /** Prefills empty slug fields from title while creating a product. */
  autoFillEmptySlugs?: boolean;
  /** `titles` = name fields only; `body` = description+; `all` = everything (default). */
  fields?: "titles" | "body" | "all";
};

function getSlugHelperText(
  locale: "en" | "ar",
  title: string,
  currentSlug: string | undefined,
  showSlugPreview: boolean,
  t: ReturnType<typeof useTranslation>,
): string | undefined {
  const predictedSlug = getPredictedProductSlug(locale, title);
  const savedSlug = currentSlug?.trim() ?? "";

  if (savedSlug) {
    if (showSlugPreview && title && predictedSlug && predictedSlug !== savedSlug) {
      return `${t.slugSuggestedFromTitle}: ${predictedSlug}`;
    }

    return undefined;
  }

  if (showSlugPreview && predictedSlug) {
    return t.slugAutoGenerated;
  }

  return undefined;
}

export function ProductTranslationFields({
  value,
  onChange,
  titleErrors,
  showSlugPreview = true,
  autoFocusFirstField = false,
  autoFillEmptySlugs = false,
  fields = "all",
}: ProductTranslationFieldsProps) {
  const t = useTranslation();
  const [activeLocale, setActiveLocale] = useState<"en" | "ar">("en");

  useEffect(() => {
    if (titleErrors?.en) setActiveLocale("en");
    else if (titleErrors?.ar) setActiveLocale("ar");
  }, [titleErrors]);

  const updateLocale = (
    locale: "en" | "ar",
    field: keyof NonNullable<ProductTranslationsInput["en"]>,
    next: string,
  ) => {
    onChange({
      ...value,
      [locale]: {
        title: value[locale]?.title ?? "",
        slug: value[locale]?.slug,
        description: value[locale]?.description ?? "",
        metaTitle: value[locale]?.metaTitle ?? "",
        metaDescription: value[locale]?.metaDescription ?? "",
        benefits: value[locale]?.benefits ?? "",
        ingredients: value[locale]?.ingredients ?? "",
        usageMethod: value[locale]?.usageMethod ?? "",
        warnings: value[locale]?.warnings ?? "",
        countryOfOrigin: value[locale]?.countryOfOrigin ?? "",
        [field]: next,
      },
    });
  };

  const updateTitle = (locale: "en" | "ar", nextTitle: string) => {
    const previousTitle = value[locale]?.title ?? "";
    const currentSlug = value[locale]?.slug;
    const shouldSyncSlug =
      !currentSlug?.trim() ||
      shouldAutoSuggestProductSlug(locale, previousTitle, currentSlug);
    const nextSlug = shouldSyncSlug ? getPredictedProductSlug(locale, nextTitle) : currentSlug;

    onChange({
      ...value,
      [locale]: {
        title: nextTitle,
        slug: nextSlug,
        description: value[locale]?.description ?? "",
        metaTitle: value[locale]?.metaTitle ?? "",
        metaDescription: value[locale]?.metaDescription ?? "",
        benefits: value[locale]?.benefits ?? "",
        ingredients: value[locale]?.ingredients ?? "",
        usageMethod: value[locale]?.usageMethod ?? "",
        warnings: value[locale]?.warnings ?? "",
        countryOfOrigin: value[locale]?.countryOfOrigin ?? "",
      },
    });
  };

  useEffect(() => {
    if (!autoFillEmptySlugs) return;

    let nextValue: ProductTranslationsInput | null = null;

    for (const locale of ["en", "ar"] as const) {
      const title = value[locale]?.title?.trim() ?? "";
      const slug = value[locale]?.slug?.trim() ?? "";
      if (!title || slug) continue;

      const predictedSlug = getPredictedProductSlug(locale, title);
      if (!predictedSlug) continue;

      nextValue ??= { ...value };
      nextValue[locale] = {
        title: value[locale]?.title ?? "",
        slug: predictedSlug,
        description: value[locale]?.description ?? "",
        metaTitle: value[locale]?.metaTitle ?? "",
        metaDescription: value[locale]?.metaDescription ?? "",
        benefits: value[locale]?.benefits ?? "",
        ingredients: value[locale]?.ingredients ?? "",
        usageMethod: value[locale]?.usageMethod ?? "",
        warnings: value[locale]?.warnings ?? "",
        countryOfOrigin: value[locale]?.countryOfOrigin ?? "",
      };
    }

    if (nextValue) {
      onChange(nextValue);
    }
  }, [
    autoFillEmptySlugs,
    onChange,
    value.ar?.slug,
    value.ar?.title,
    value.en?.slug,
    value.en?.title,
  ]);

  const showTitles = fields === "all" || fields === "titles";
  const showBody = fields === "all" || fields === "body";

  const renderLocaleFields = (locale: "en" | "ar") => {
    const title = value[locale]?.title?.trim() ?? "";
    const slugHelper = getSlugHelperText(
      locale,
      title,
      value[locale]?.slug,
      showSlugPreview && showTitles,
      t,
    );

    return (
      <div className="space-y-4">
        {showTitles ? (
          <>
            <TextField
              label={locale === "en" ? t.titleEnglish : t.titleArabic}
              value={value[locale]?.title ?? ""}
              onChange={(event) => updateTitle(locale, event.target.value)}
              error={titleErrors?.[locale]}
              dir={locale === "ar" ? "rtl" : undefined}
              autoFocus={autoFocusFirstField && locale === "en"}
              required
            />
            <TextField
              label={locale === "en" ? t.slugEnglish : t.slugArabic}
              value={value[locale]?.slug ?? ""}
              onChange={(event) => updateLocale(locale, "slug", event.target.value)}
              helperText={slugHelper}
              dir={locale === "ar" ? "rtl" : undefined}
            />
          </>
        ) : null}
        {showBody ? (
          <>
            <TextAreaField
              label={locale === "en" ? t.descriptionEnglish : t.descriptionArabic}
              value={value[locale]?.description ?? ""}
              onChange={(event) => updateLocale(locale, "description", event.target.value)}
              dir={locale === "ar" ? "rtl" : undefined}
            />

            <TextAreaField
              label={t.benefits}
              value={value[locale]?.benefits ?? ""}
              onChange={(event) => updateLocale(locale, "benefits", event.target.value)}
              dir={locale === "ar" ? "rtl" : undefined}
            />
            <TextAreaField
              label={t.ingredients}
              value={value[locale]?.ingredients ?? ""}
              onChange={(event) => updateLocale(locale, "ingredients", event.target.value)}
              dir={locale === "ar" ? "rtl" : undefined}
            />
            <TextAreaField
              label={t.usageMethod}
              value={value[locale]?.usageMethod ?? ""}
              onChange={(event) => updateLocale(locale, "usageMethod", event.target.value)}
              dir={locale === "ar" ? "rtl" : undefined}
            />
            <TextAreaField
              label={t.warnings}
              value={value[locale]?.warnings ?? ""}
              onChange={(event) => updateLocale(locale, "warnings", event.target.value)}
              dir={locale === "ar" ? "rtl" : undefined}
            />
            <TextField
              label={t.countryOfOrigin}
              value={value[locale]?.countryOfOrigin ?? ""}
              onChange={(event) => updateLocale(locale, "countryOfOrigin", event.target.value)}
              dir={locale === "ar" ? "rtl" : undefined}
            />
          </>
        ) : null}
      </div>
    );
  };

  return (
    <Tabs value={activeLocale} onValueChange={(next) => setActiveLocale(next as "en" | "ar")}>
      <TabsList className="grid w-full grid-cols-2">
        <TabsTrigger value="en">{t.tabEnglish}</TabsTrigger>
        <TabsTrigger value="ar">{t.tabArabic}</TabsTrigger>
      </TabsList>
      <TabsContent value="en" className="mt-4">
        {renderLocaleFields("en")}
      </TabsContent>
      <TabsContent value="ar" className="mt-4">
        {renderLocaleFields("ar")}
      </TabsContent>
    </Tabs>
  );
}
