export type Permission = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];

export type CrudPermissions = {
  manage: Permission;
  create: Permission;
  update: Permission;
  delete: Permission;
  show: Permission;
};

const CRUD_ACTIONS = ["CREATE", "UPDATE", "DELETE", "SHOW"] as const;

/** Expand MANAGE_* into related CRUD permissions. */
export function expandManagePermissions(permissions: string[]): string[] {
  const expanded = new Set(permissions);

  for (const permission of permissions) {
    if (!permission.startsWith("MANAGE_")) continue;

    const resource = permission.slice("MANAGE_".length);
    for (const action of CRUD_ACTIONS) {
      expanded.add(`PERMISSION_${action}_${resource}`);
    }

    if (permission === "MANAGE_PRODUCT") {
      expanded.add("PERMISSION_IMPORT_PRODUCT");
    }

    // Backend download endpoints accept MANAGE_* | PERMISSION_DOWNLOAD_*.
    if (permission === "MANAGE_ORDER") {
      expanded.add("PERMISSION_DOWNLOAD_ORDER");
    }
    if (permission === "MANAGE_INVOICE") {
      expanded.add("PERMISSION_DOWNLOAD_INVOICE");
    }
    if (permission === "MANAGE_WHATSAPP_TEMPLATE") {
      expanded.add("PERMISSION_SEND_TEST_WHATSAPP_TEMPLATE");
    }
  }

  return Array.from(expanded);
}

/** Resolve CRUD permission names for a MANAGE_* permission. */
export function getCrudPermissionsForManage(managePermission: Permission): CrudPermissions {
  const resource = managePermission.slice("MANAGE_".length);

  return {
    manage: managePermission,
    create: `PERMISSION_CREATE_${resource}` as Permission,
    update: `PERMISSION_UPDATE_${resource}` as Permission,
    delete: `PERMISSION_DELETE_${resource}` as Permission,
    show: `PERMISSION_SHOW_${resource}` as Permission,
  };
}

